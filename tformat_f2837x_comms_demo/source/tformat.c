void tformat_init(void) {
    //
    // Configure the GPIO, XBAR and CLB MUX
    // Configure the CLB and SPI
    // Configure the SPI interrupt and enable the SPI
    //
#if defined(PM_TFORMAT_CRC_TABLE)

    //
    // If the C28x will be generating CRC, then initialize
    // the lookup table.
    //
    PM_tformat_generateCRCTable(PM_TFORMAT_NBITS_POLY,
                                PM_TFORMAT_POLY,
                                tformatCRCtable);
#endif

    //
    // Configure the CLB tile(s) for T-format
    //
    PM_tformat_setupPeriph();
    PM_tformat_setFreq(TFORMAT_FREQ_DIVIDER);

    //
    // These functions are generated by SysCfg in the system example
    // Refer to tformat_<device>.syscfg
    // The generated source is in the syscfg/board.c file in the build
    // directory
    //
    // Some devices do not have a CLB_OUTPUTXBAR and CLB_INPUTXBAR
    // In this case the device OUTPUTXBAR and INPUTXBAR are used.
    //
    GPIO_init();
    PinMux_init();
#if !defined(PM_TFORMAT_USE_CLB_INPUTXBAR)
    CLBXBAR_init();
    INPUTXBAR_init();
    #if !defined(_F28004X)
        OUTPUTXBAR_init();
    #endif
    #if defined(_F28004X) && !defined(_LAUNCHXL_F280049C)
        OUTPUTXBAR_init();
    #endif
#elif defined(PM_TFORMAT_USE_CLB_INPUTXBAR)
    CLB_INPUTXBAR_init();
    CLB_OUTPUTXBAR_init();
#else
    #error Update the GPIO, MUX, XBAR calls for the specific device.
#endif
    tformat_initSPIFIFO(DEVICE_LSPCLK_FREQ);
    Interrupt_register(PM_TFORMAT_INT_SPI_RX, &tformat_spiRxISR);
    Interrupt_enable(PM_TFORMAT_INT_SPI_RX);
    SPI_clearInterruptStatus(PM_TFORMAT_SPI, SPI_INT_RXFF);
    SPI_enableInterrupt(PM_TFORMAT_SPI, SPI_INT_RXFF);
    SPI_enableModule(PM_TFORMAT_SPI);

    //
    // Power up the T-Format 5v supply
    //
    GPIO_writePin(TFORMAT_GPIO_PWRCTRL, 1);
    DEVICE_DELAY_US(TFORMAT_POWER_ON_DELAY_US);
}


void tformat_spiRxISR(void)
{
    uint16_t i;
    tformatSpiRxIsrTicker++;
//
// [doc-spi-isr-start]
//
    #pragma MUST_ITERATE(5, 12, 1)
    for (i = 0; i < tformatData.fifoLevel; i++)
    {
        tformatRxData[i] = SPI_readDataNonBlocking(PM_TFORMAT_SPI) & 0xFF;
    }

//
// [doc-spi-isr-end]
//
    SPI_clearInterruptStatus(PM_TFORMAT_SPI, SPI_INT_RXFF_OVERFLOW);
    SPI_clearInterruptStatus(PM_TFORMAT_SPI, SPI_INT_RXFF);
    Interrupt_clearACKGroup(INTERRUPT_ACK_GROUP6);
    tformatData.dataReady = true;
}

#if defined(_F2837X)
void tformat_configEPWM4(void) {

    //
    // Configure EPWM4 to drive a default value on GPIO7
    // before the CLB tile takes over the output.
    //
    // The CLB Tile_4.out2 will override the EPWM4B output
    // to reach GPIO7.  The PWM functionality itself is not used
    // only the output enable is leveraged by the CLB.
    //
    EPWM_setTripZoneAction(EPWM4_BASE,
                           EPWM_TZ_ACTION_EVENT_TZB,
                           EPWM_TZ_ACTION_HIGH);
    EPWM_forceTripZoneEvent(EPWM4_BASE, EPWM_TZ_FORCE_EVENT_OST);
}
#endif


void
tformat_initSPIFIFO(uint32_t devLSPCLKFreq)
{

    SPI_disableModule(PM_TFORMAT_SPI);
    SPI_disableLoopback(PM_TFORMAT_SPI);
#if defined(PM_TFORMAT_USE_INCLUSIVE_TERMINOLOGY)
    SPI_setConfig(PM_TFORMAT_SPI, devLSPCLKFreq, SPI_PROT_POL1PHA0,
                SPI_MODE_PERIPHERAL, 500000, PM_TFORMAT_FIFO_WORD_BITS);
#else
    SPI_setConfig(PM_TFORMAT_SPI, devLSPCLKFreq, SPI_PROT_POL1PHA0,
                SPI_MODE_SLAVE, 500000, PM_TFORMAT_FIFO_WORD_BITS);
#endif
    SPI_clearInterruptStatus(PM_TFORMAT_SPI, SPI_INT_RX_OVERRUN |
                             SPI_INT_RX_DATA_TX_EMPTY | SPI_INT_RXFF |
                             SPI_INT_RXFF_OVERFLOW | SPI_INT_TXFF);
    SPI_enableFIFO(PM_TFORMAT_SPI);
    SPI_setFIFOInterruptLevel(PM_TFORMAT_SPI, SPI_FIFO_TX3, SPI_FIFO_RX3);
    SPI_setEmulationMode(PM_TFORMAT_SPI, SPI_EMULATION_FREE_RUN);
    SPI_enableModule(PM_TFORMAT_SPI);
    SPI_resetTxFIFO(PM_TFORMAT_SPI);
    SPI_resetRxFIFO(PM_TFORMAT_SPI);

    SPI_enableInterrupt(PM_TFORMAT_SPI, SPI_INT_RX_OVERRUN |
                        SPI_INT_RX_DATA_TX_EMPTY | SPI_INT_RXFF
                        | SPI_INT_RXFF_OVERFLOW);
    SPI_enableInterrupt(PM_TFORMAT_SPI, SPI_INT_RXFF);
}


uint16_t
tformat_checkError(uint16_t controlFieldID)
{
    uint16_t errorFlag = PM_TFORMAT_PASS;

    //
    // Check sent/received controlField (data ID)
    // Check calculated CRC against received CRC
    //
    if(commandData.controlField != tformatData.controlField)
    {
        errorFlag = 1;
        errorData.idCheckError = 1;
    }
    if(tformatData.crcCheck != tformatData.crcField)
    {
        errorFlag = 1;
        errorData.crcCheckError = 1;
    }

    //
    // If this was an EEPROM write:
    // - Check sent Address against received Address (ADF)
    // - Check sent Data against received Data (EDF)
    //
    if(controlFieldID == PM_TFORMAT_CFID6)
    {
        if(commandData.eepromAddress != tformatData.eepromAddressField)
        {
            errorFlag = 1;
            errorData.eepromAddressError = 1;
        }

        if(commandData.eepromData != tformatData.eepromWrDataField)
        {
            errorFlag = 1;
            errorData.eepromDataError = 1;
        }
    }

    //
    // If this was an EEPROM read:
    // - Check sent Address against received Address (ADF)
    // - Check expected data against received data (EDF)
    //
    if(controlFieldID == PM_TFORMAT_CFIDD)
    {
        if(commandData.eepromAddress != tformatData.eepromAddressField)
        {
            errorFlag = 1;
            errorData.eepromAddressError = 1;
        }
        if(commandData.eepromData != tformatData.eepromRdDataField)
        {
            errorFlag = 1;
            errorData.eepromDataError = 1;
        }
    }

    return(errorFlag);
}

